package business

import (
	"errors"
	"fmt"

	chatv1 "buf.build/gen/go/stawi/chat/protocolbuffers/go/chat/v1"
	"buf.build/go/protovalidate"
	"connectrpc.com/connect"

	"github.com/stawilabs/chat/apps/default/service/models"
)

// validateStawiPayload checks a Stawi act a client sends before anything is
// relayed or stored. Every client ingress path (SendEvent, the Live stream's
// room events, and anything else that reaches SendEvents) passes through it.
//
// It fails closed on two independent layers:
//
//   - Shape is protovalidate over the whole event, the same rules the RPC
//     validation interceptor applies. Chat keeps no hand-written copy of those
//     rules, so the two cannot drift.
//   - Ingress policy is what the proto cannot say: the declared type must be
//     exactly the type of the populated member (the payload converter would
//     otherwise infer or drop the type and store an unchecked Stawi payload),
//     outcomes are server-generated only, a genesis is set by the server
//     only, and the event type is ROOM_EVENT_TYPE_EVENT.
//
// Chat checks shape and policy only. Whether the act is allowed is the chain's
// decision: settlement simulates the call before relaying it and the chain
// verifies the signature.
func validateStawiPayload(reqEvt *chatv1.RoomEvent) error {
	payload := reqEvt.GetPayload()
	declared := payload.GetType()
	member := models.StawiMemberType(payload)

	if !models.IsStawiPayload(declared) && member == chatv1.PayloadType_PAYLOAD_TYPE_UNSPECIFIED {
		return nil
	}

	if declared != member {
		return invalidStawiPayload(fmt.Errorf(
			"payload type %s does not match the populated content (%s)", declared, member))
	}

	if declared == chatv1.PayloadType_PAYLOAD_TYPE_STAWI_CALL_OUTCOME {
		return invalidStawiPayload(errors.New("call outcomes are generated by the server and cannot be sent"))
	}

	if reqEvt.GetType() != chatv1.RoomEventType_ROOM_EVENT_TYPE_EVENT {
		return invalidStawiPayload(errors.New("stawi payload event type must be ROOM_EVENT_TYPE_EVENT"))
	}

	content := models.StawiContent(payload)
	if content == nil {
		return invalidStawiPayload(fmt.Errorf("payload content for %s is required", declared))
	}

	if conversion, ok := content.(*chatv1.StawiRoomConversionContent); ok && conversion.GetGenesis() != nil {
		return invalidStawiPayload(errors.New("genesis is set by the server; leave it empty"))
	}

	if err := protovalidate.Validate(reqEvt); err != nil {
		return invalidStawiPayload(err)
	}

	return nil
}

func invalidStawiPayload(err error) error {
	return connect.NewError(connect.CodeInvalidArgument, err)
}
